'use strict';
const fs=require('fs');
const vm=require('vm');
const assert=require('assert/strict');
const root=require('path').resolve(__dirname,'..');
const listeners={};
const makeNode=()=>({hidden:false,children:[],style:{},attributes:{},append(n){this.children.push(n)},setAttribute(k,v){this.attributes[k]=v},getAttribute(k){return this.attributes[k]},focus(){},removeAttribute(k){delete this[k]},scrollIntoView(){},addEventListener(k,v){this['on'+k]=v}});
const elems={chatCamera:makeNode(),chatCameraPanel:makeNode(),chatCameraFrame:makeNode(),chatCameraClose:makeNode(),coachStatus:makeNode(),coachHistory:makeNode()};
elems.chatCameraPanel.hidden=true;
const frames=[];
elems.chatCameraFrame.contentWindow={postMessage(msg,origin){frames.push({msg,origin})}};
const window={location:{href:'https://lab.example/agent_chat.php',origin:'https://lab.example'},addEventListener(k,v){(listeners[k]??=[]).push(v)}};
const document={getElementById:id=>elems[id]||null,createElement:makeNode};
vm.runInNewContext(fs.readFileSync(root+'/assets/agent_chat_camera.js','utf8'),{window,document,URL});
function emit(name,ev={}){for(const fn of listeners[name]||[])fn(ev)}
assert.equal(elems.chatCameraFrame.src,undefined,'camera must not load automatically');
emit('pizza-chat-photo-command');
assert.match(elems.coachStatus.textContent,/Open the camera/);
emit('pizza-chat-camera-toggle');
assert.equal(elems.chatCameraPanel.hidden,false);
assert.match(elems.chatCameraFrame.src,/embedded=1/);
assert.equal(elems.chatCamera.attributes['aria-expanded'],'true');
emit('pizza-chat-photo-command');
assert.equal(frames.at(-1).msg.type,'take-photo');
assert.equal(frames.at(-1).origin,'https://lab.example');
emit('message',{source:{},origin:'https://lab.example',data:{channel:'pizza-lab:camera',type:'photo',media_id:5,evidence_id:2}});
assert.equal(elems.coachHistory.children.length,0,'reject other frame');
emit('message',{source:elems.chatCameraFrame.contentWindow,origin:'https://evil.example',data:{channel:'pizza-lab:camera',type:'photo',media_id:5,evidence_id:2}});
assert.equal(elems.coachHistory.children.length,0,'reject other origin');
emit('message',{source:elems.chatCameraFrame.contentWindow,origin:'https://lab.example',data:{channel:'pizza-lab:camera',type:'photo',media_id:5,evidence_id:2,confidence:'low'}});
assert.equal(elems.coachHistory.children.length,1,'show saved photo');
emit('message',{source:elems.chatCameraFrame.contentWindow,origin:'https://lab.example',data:{channel:'pizza-lab:camera',type:'analysis',media_id:5,summary:'Sample only',confidence:'low'}});
assert.equal(elems.coachHistory.children[0].children.length,6);
emit('pizza-chat-mic-start');
assert.equal(frames.at(-1).msg.type,'pause-voice');
elems.chatCameraClose.onclick();
assert.equal(elems.chatCameraPanel.hidden,true);
assert.equal(elems.chatCameraFrame.src,undefined,'unload releases resources');
console.log('PASS: camera opens in chat, no automatic media access, same-origin messages, voice routing and teardown');
