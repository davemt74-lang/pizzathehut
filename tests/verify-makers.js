/* Source/UI contract test for batch maker attribution. Does not exercise real MySQL. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const source=read('assets/app.js');
const ctx={console,window:{PIZZA_LAB:{user_id:2,role:'team_member',user:'Chef B'}}};
vm.createContext(ctx);
vm.runInContext(source.slice(0,source.indexOf('function mediaHtml')),ctx);
const run=x=>vm.runInContext(x,ctx);
run(`state.data.recipes=[{id:8,name:'Gelato v1.0',flour_g:10000}];
state.data.batch_makers=[{id:1,display_name:'Owner',is_active:1},{id:2,display_name:'Chef <B>',is_active:1},{id:3,display_name:'Former employee',is_active:0}];
state.data.batches=[{id:5,recipe_id:8,recipe_name:'Gelato v1.0',batch_code:'PL-ABC234',stage:'bulk',made_by_user_id:2,made_by_name:'Chef <B>',recorded_by_user_id:1,recorded_by_name:'Owner'}];`);
const form=run('batchForm({recipe_id:8})');
assert.match(form,/name="made_by_user_id" required/);
assert.match(form,/<option value="2" selected>Chef &lt;B&gt;<\/option>/);
assert.doesNotMatch(form,/value="3"/);
assert.match(form,/Defaults to your login/);
const saved=run('batchForm(state.data.batches[0])');
assert.match(saved,/<option value="2" selected>Chef &lt;B&gt;<\/option>/);
assert.match(run('batchesView()'),/Made by: Chef &lt;B&gt;/);
assert.match(run('batchesView()'),/id="batchMakerFilterSelect"/);
run(`state.batchMakerFilter='1'`);
assert.doesNotMatch(run('batchesView()'),/PL-ABC234/);
run(`state.batchMakerFilter='2'`);
assert.match(run('batchesView()'),/PL-ABC234/);
run(`state.batchMakerFilter='all'`);
const legacy=run('batchForm({id:9,recipe_id:8,made_by_user_id:null})');
assert.match(legacy,/Not recorded \(older batch\)/);
assert.match(run('batchForm({id:10,recipe_id:8,made_by_user_id:3})'),/Former employee \(inactive; historical\)/);
run(`state.activeBatch={id:5,batch_code:'PL-ABC234',recipe_id:8,recipe_name:'Gelato v1.0',recipe_at_mixing:{name:'Gelato v1.0',flour_g:10000},stage:'bulk',pizzas:[],events:[],analytics:{pizzas:0},notes:null,made_by_name:'Chef <B>',recorded_by_name:'Owner',planned_steps:[],step_logs:[],containers:[],temperatures:[],usage:[],waste:[],process_analytics:{}}`);
const detail=run('batchDetailView()');
assert.match(detail,/Made by: Chef &lt;B&gt;/);
assert.match(detail,/Recorded by: Owner/);
assert.doesNotMatch(detail,/Chef <B>/);
const api=read('api.php'),upgrade=read('upgrade.php'),schema=read('schema.sql');
assert.match(api,/\$makerRaw=\$d\['made_by_user_id'\]/);
assert.match(api,/\?\(\$old\['made_by_user_id'\]===null\?null:/);
assert.match(api,/\):auth\(\)/);
assert.match(api,/SELECT id,is_active FROM users WHERE id=/);
assert.match(api,/Choose an active team member as the dough maker/);
assert.match(api,/INSERT INTO dough_batches \(batch_code,recipe_id,recipe_snapshot,process_steps_snapshot,made_by_user_id,recorded_by_user_id/);
assert.match(api,/\$makerId,auth\(\)/);
assert.match(api,/UPDATE dough_batches SET made_by_user_id=/);
assert.doesNotMatch(api,/UPDATE dough_batches SET recorded_by_user_id=/);
assert.match(schema,/FOREIGN KEY \(made_by_user_id\) REFERENCES users\(id\) ON DELETE RESTRICT/);
assert.match(schema,/FOREIGN KEY \(recorded_by_user_id\) REFERENCES users\(id\) ON DELETE RESTRICT/);
assert.match(upgrade,/if \(!\$columnExists\('dough_batches','made_by_user_id'\)\)/);
assert.match(upgrade,/if \(!\$columnExists\('dough_batches','recorded_by_user_id'\)\)/);
assert.match(upgrade,/SELECT COUNT\(\*\) FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE/);
assert.doesNotMatch(upgrade,/UPDATE dough_batches SET made_by_user_id=/);
console.log('PASS: maker defaults, team selection, HTML escaping, historical unknowns, recorder provenance, FK and migrations');
